import { test } from "node:test";
import assert from "node:assert/strict";
import { bahtText } from "./baht-text.ts";
const cases: [number, string][] = [
  [0, "ศูนย์บาทถ้วน"], [100, "หนึ่งบาทถ้วน"], [1100, "สิบเอ็ดบาทถ้วน"], [2100, "ยี่สิบเอ็ดบาทถ้วน"], [2000, "ยี่สิบบาทถ้วน"],
  [10100, "หนึ่งร้อยเอ็ดบาทถ้วน"], [15000, "หนึ่งร้อยห้าสิบบาทถ้วน"], [159000, "หนึ่งพันห้าร้อยเก้าสิบบาทถ้วน"],
  [745000, "เจ็ดพันสี่ร้อยห้าสิบบาทถ้วน"], [100000000, "หนึ่งล้านบาทถ้วน"], [100100000, "หนึ่งล้านหนึ่งพันบาทถ้วน"],
  [110000000, "หนึ่งล้านหนึ่งแสนบาทถ้วน"], [1100000000, "สิบเอ็ดล้านบาทถ้วน"], [2100000000, "ยี่สิบเอ็ดล้านบาทถ้วน"],
  [100000000000, "หนึ่งพันล้านบาทถ้วน"], [150, "หนึ่งบาทห้าสิบสตางค์"], [25, "ยี่สิบห้าสตางค์"], [101, "หนึ่งบาทหนึ่งสตางค์"], [111, "หนึ่งบาทสิบเอ็ดสตางค์"],
];
for (const [n, s] of cases) test(`${n} → ${s}`, () => assert.equal(bahtText(n), s));
test("ค่าติดลบ/ทศนิยม → error", () => { assert.throws(() => bahtText(-1)); assert.throws(() => bahtText(1.5)); });
